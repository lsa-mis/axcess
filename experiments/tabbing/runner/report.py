"""Render ``results.md`` from a run payload.

Generated output only. Every table here is a direct projection of ``raw.json``
with no interpretation, so the hand-written report can cite it and anyone can
recompute it. Interpretation belongs in the report, which a human maintains.

Formatting rule throughout: a metric that does not apply prints as an em dash,
never as ``0.0``. Zero means "got it all wrong"; the dash means "the question
does not apply here", and conflating them is how a table lies quietly.
"""

from __future__ import annotations

from typing import Any


def _pct(value: float | None) -> str:
    return "—" if value is None else f"{value * 100:.1f}%"


def _num(value: Any) -> str:
    return "—" if value is None else str(value)


def render(payload: dict[str, Any]) -> str:
    run = payload.get("run", {})
    lines: list[str] = []

    lines.append("# Keyboard differential — generated results")
    lines.append("")
    lines.append("Generated by `experiments/tabbing/runner/main.py`. Do not edit;")
    lines.append("each run uses distinct files. Interpretation lives in `REPORT.md`.")
    lines.append("")

    lines.append("## Run")
    lines.append("")
    lines.append("| field | value |")
    lines.append("|---|---|")
    lines.append(f"| label | `{run.get('label', '?')}` |")
    lines.append(f"| started (UTC) | {run.get('started_utc', '?')} |")
    lines.append(f"| corpus sha256 | `{str(run.get('corpus_sha256', ''))[:32]}…` |")
    detector = run.get("detector_sha256", {})
    lines.append(f"| detector sha256 | `{str(detector.get('_combined', ''))[:32]}…` |")
    versions = run.get("versions", {})
    lines.append(f"| python | {versions.get('python', '?')} |")
    lines.append(f"| playwright | {versions.get('playwright', '?')} |")
    lines.append(f"| chromium | {versions.get('chromium', '?')} |")
    lines.append(f"| wall time | {_num(run.get('wall_seconds'))} s |")
    lines.append(f"| errors | {len(run.get('errors', []))} |")
    lines.append("")

    if not run.get("valid", True):
        lines.extend(["**Invalid run: do not use these observations as accuracy evidence.**", ""])
        lines.extend(str(reason) for reason in run.get("invalid_reasons", []))
        lines.append("")

    lines.append("## Scores")
    lines.append("")
    lines.append(
        "`recall` counts undecided positives against the detector; "
        "`recall*` is the same figure over decided probes only."
    )
    lines.append("")
    header = (
        "| mode | cohort | viewport | TP | FP | FN | TN | unknown (pos/neg) "
        "| precision | recall | recall* | F1 | coverage |"
    )
    lines.append(header)
    lines.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for score in payload.get("scores", []):
        unknown = f"{score.get('unknown_positive', 0)}/{score.get('unknown_negative', 0)}"
        lines.append(
            f"| {score.get('mode')} | {score.get('cohort')} | {score.get('viewport')} "
            f"| {score.get('tp')} | {score.get('fp')} | {score.get('fn')} | {score.get('tn')} "
            f"| {unknown} | {_pct(score.get('precision'))} | {_pct(score.get('recall'))} "
            f"| {_pct(score.get('recall_conditional'))} | {_pct(score.get('f1'))} "
            f"| {_pct(score.get('classified_coverage'))} |"
        )
    lines.append("")

    lines.append("## Candidate recall (the ceiling on candidate-gated recall)")
    lines.append("")
    lines.append("The oracle cannot confirm a defect the cheap pass never proposed.")
    lines.append("")
    lines.append("| viewport | real defects | proposed | recall | missed |")
    lines.append("|---|---|---|---|---|")
    for row in payload.get("candidate_recall", []):
        missed = ", ".join(row.get("missed", [])) or "—"
        recall = row["proposed"] / row["positives"] if row.get("positives") else None
        lines.append(
            f"| {row.get('viewport')} | {row.get('positives')} | {row.get('proposed')} "
            f"| {_pct(recall)} | {missed} |"
        )
    lines.append("")

    errors = run.get("errors", [])
    if errors:
        lines.append("## Errors")
        lines.append("")
        lines.append("| page | stage | error |")
        lines.append("|---|---|---|")
        for err in errors[:50]:
            message = str(err.get("error", "")).replace("|", "\\|")[:120]
            lines.append(f"| {err.get('page')} | {err.get('stage')} | {message} |")
        lines.append("")

    undecided = _collect_undecided(payload)
    if undecided:
        lines.append("## Undecided probes")
        lines.append("")
        lines.append("Neither passed nor failed. Counted against recall when the truth")
        lines.append("says they were real defects.")
        lines.append("")
        lines.append("| probe | viewport | reason |")
        lines.append("|---|---|---|")
        for probe in undecided[:80]:
            reason = probe.get("uncertainty_reason") or "—"
            lines.append(f"| {probe['id']} | {probe['viewport']} | {reason} |")
        lines.append("")

    dismissals = payload.get("dismissals", [])
    if dismissals:
        lines.append("## Equivalence dismissals")
        lines.append("")
        lines.append("Findings dropped because a keyboard-reachable control on the **same page**")
        lines.append("produced the same observed effect signature in the same viewport.")
        lines.append("")
        lines.append("| probe | page | viewport | dismissed by | effect |")
        lines.append("|---|---|---|---|---|")
        for row in dismissals[:50]:
            lines.append(
                f"| {row.get('probe')} | {row.get('page')} | {row.get('viewport')} "
                f"| {row.get('dismissed_by')} | `{row.get('signature')}` |"
            )
        lines.append("")

    lines.append("## Tab order")
    lines.append("")
    lines.append("| page @ viewport | presses | probes found | capped |")
    lines.append("|---|---|---|---|")
    for key, info in sorted(payload.get("tab_orders", {}).items()):
        capped = "**yes**" if info.get("capped") else "no"
        lines.append(f"| {key} | {info.get('presses')} | {info.get('found')} | {capped} |")
    lines.append("")

    return "\n".join(lines) + "\n"


def _collect_undecided(payload: dict[str, Any]) -> list[dict[str, Any]]:
    return [p for p in payload.get("probes", []) if p.get("predicted") == "unknown"]
